// 실험실(js/grok.js의 실험실_목록·실험실_항목탭) 상태 표시 정합성 검증.
// ─────────────────────────────────────────────────────────────────────────
// 2026-08-22 발견: '끝말잇기'가 실플레이 가능(서바이벌·아케이드 + 우리말샘 실연동 완료,
// 홈 포탈로 진입 가능)인데도 실험실에는 '예정'으로 남아 있어, 실험실을 연 사용자에게
// "🔒 준비 중인 기능입니다"라고 없는 기능처럼 안내하고 있었다. 이런 어긋남이 다시
// 생기지 않도록, "상태가 '가능'이면 실제로 열리는가"를 회귀로 고정한다.
const { load, makeHarness } = require('./load.cjs');

const { assert, finish } = makeHarness('실험실 상태 표시 정합성');

load((win) => {
  const ev = (code) => win.eval(code);
  const doc = win.document;

  // (1) 끝말잇기는 완성된 기능이므로 '예정'이면 안 된다
  const 끝말잇기 = ev("JSON.stringify(실험실_목록.find(x => x.이름 === '끝말잇기'))");
  const it = JSON.parse(끝말잇기 || 'null');
  assert('실험실에 끝말잇기 항목이 있다', !!it);
  assert('끝말잇기 상태가 "가능"이다(완성된 기능을 예정으로 두지 않는다)',
    it && it.상태 === '가능', it && it.상태);
  assert('끝말잇기에 연결 함수(잇는_포탈탭)가 지정돼 있다', it && it.열기 === '잇는_포탈탭');
  assert('지정된 연결 함수가 실제로 존재한다', typeof win.잇는_포탈탭 === 'function');

  // (2) 상태가 '가능'인 항목은 개발자 모드가 아니어도 실제로 열려야 한다
  //     (티저로 막아 두면 사용자가 없는 기능으로 오해한다 — 이번 결함의 핵심)
  ev("사용자.개발자모드 = false; 사용자.잇는개방 = true;");
  let 이동호출됨 = false;
  win.잇는_이동 = () => { 이동호출됨 = true; };
  ev("실험실_열기(); 실험실_항목탭(0);");
  assert('비개발자도 "가능" 항목을 탭하면 실제 기능으로 연결된다', 이동호출됨);

  // (3) '예정' 항목은 여전히 티저로 막힌다(기존 동작 유지 — 과잉 개방 방지)
  const 예정인덱스 = ev("실험실_목록.findIndex(x => x.상태 === '예정')");
  assert('아직 "예정"인 항목이 남아 있다(테스트 전제)', 예정인덱스 >= 0);
  ev(`실험실_열기(); 실험실_항목탭(${예정인덱스});`);
  assert('"예정" 항목은 준비 중 안내로 막힌다',
    doc.body.innerHTML.includes('준비 중인 기능입니다'));

  // (4) 목록에 렌더된 상태 뱃지가 데이터와 일치한다(화면과 데이터 어긋남 방지)
  ev("실험실_열기();");
  const html = doc.body.innerHTML;
  const 상태들 = JSON.parse(ev("JSON.stringify(실험실_목록.map(x => x.상태))"));
  assert('실험실 목록에 모든 항목의 상태 뱃지가 렌더된다',
    상태들.every(s => html.includes(s)), 상태들.join(','));

  process.exit(finish() > 0 ? 1 : 0);
});
