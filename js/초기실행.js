const 테스트진입_시퀀스 = 'yyyyynny';
let 테스트진입_버퍼 = '';
function 테스트진입_키감지(ev){
  // 입력창에 타이핑 중일 때는 무시 (이름·질문·구어 교정 등 정상 입력 방해 방지)
  const t = ev.target;
  if(t && (t.tagName==='INPUT' || t.tagName==='TEXTAREA' || t.isContentEditable)) return;
  const k = (ev.key || '').toLowerCase();
  if(k.length !== 1) return;  // Shift·Enter 등 특수키 무시
  테스트진입_버퍼 = (테스트진입_버퍼 + k).slice(-테스트진입_시퀀스.length);
  if(테스트진입_버퍼 === 테스트진입_시퀀스){
    테스트진입_버퍼 = '';
    게스트로그인();
  }
}

