// α11: [꾸준한 발걸음] 단계별 EXP 획득 배율 (KNOWLEDGE 14 — 현재 도달 단계의 배율만 적용)
// 세션10: 임계값을 업적_정의.steady와 동일하게 ×1.45 디버프(둘이 같은 단계표를 공유하는 설계 — KNOWLEDGE 14)
function EXP배율(연속일){
  if(연속일>=29) return 1.22;
  if(연속일>=21) return 1.15;
  if(연속일>=15) return 1.09;
  if(연속일>=10) return 1.07;
  if(연속일>=7)  return 1.05;
  if(연속일>=5)  return 1.03;
  if(연속일>=3)  return 1.01;
  return 1;
}

// EXP 획득 + 레벨업 처리 + Firestore 저장 — 반환값: 배율 적용된 실제 획득량
function EXP획득(양, 사유){
  학습일갱신();
  const 실획득 = Math.round(양 * EXP배율(사용자.연속학습일 || 0));
  사용자.총누적EXP = (사용자.총누적EXP || 0) + 실획득;  // Lv.70 이후에도 계속 누적 (KNOWLEDGE 13-1)
  let 레벨업됨 = false;
  if(curLv < 최대레벨){
    curExp += 실획득;
    while(curExp >= maxExp && curLv < 최대레벨){
      curExp -= maxExp;
      curLv++;
      maxExp = expForLevel(curLv);
      레벨업됨 = true;
    }
    // α2: Lv.70 하드 캡 — 도달 후 현재EXP는 바 최대치에서 고정
    if(curLv >= 최대레벨) curExp = Math.min(curExp, maxExp);
  }
  사용자.레벨 = curLv;
  사용자.현재EXP = curExp;
  사용자데이터_저장({레벨:curLv, 현재EXP:curExp, 총누적EXP:사용자.총누적EXP});
  if(레벨업됨) 레벨업팝업(curLv);
  밤학습_체크();   // [밤의 사색가] 00:00~04:00 학습 — 일 1회 카운트
  탐닉_체크();     // [지식의 탐닉자] 세션 30분 연속 학습
  업적_검사();     // 레벨·연속일 변동 → 업적 검사 (재귀는 내부 플래그로 차단)
  if(curScreen==='sh') afterNav('sh');  // 홈 EXP 바 즉시 갱신
  return 실획득;
}

// [밤의 사색가] — 00:00~04:00 사이 학습 기록 생성 시 +1 (일 1회, KNOWLEDGE 14)
// 신규 한글 필드: 밤학습수·마지막밤기록일 (13-1 규칙에 따라 추가 — 보고됨)
function 밤학습_체크(){
  const 시 = new Date().getHours();
  if(시 >= 4) return;
  const 오늘 = 오늘날짜_로컬(0);
  if(사용자.마지막밤기록일 === 오늘) return;
  사용자.마지막밤기록일 = 오늘;
  사용자.밤학습수 = (사용자.밤학습수 || 0) + 1;
  사용자데이터_저장({밤학습수:사용자.밤학습수, 마지막밤기록일:오늘});
}

// [지식의 탐닉자] — 세션 시작부터 30분 이상 연속 학습 시 단발 달성 (KNOWLEDGE 14)
