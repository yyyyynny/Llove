// 로컬(기기 시간대) 기준 YYYY-MM-DD — toISOString()은 UTC라 한국 시간 자정 경계가 9시간 어긋남
function 오늘날짜_로컬(편차일){
  const d = new Date(Date.now() + (편차일 || 0) * 86400000);
  return d.getFullYear() + '-' + String(d.getMonth()+1).padStart(2,'0') + '-' + String(d.getDate()).padStart(2,'0');
}

// 연속·총 학습일 갱신 — 하루 1회만 동작 (KNOWLEDGE 13-1)
function 학습일갱신(){
  const 오늘 = 오늘날짜_로컬(0);
  if(사용자.마지막학습일 === 오늘) return;
  const 어제 = 오늘날짜_로컬(-1);
  사용자.연속학습일 = (사용자.마지막학습일 === 어제) ? (사용자.연속학습일 || 0) + 1 : 1;
  사용자.총학습일 = (사용자.총학습일 || 0) + 1;
  사용자.마지막학습일 = 오늘;
  사용자데이터_저장({연속학습일:사용자.연속학습일, 총학습일:사용자.총학습일, 마지막학습일:오늘});
}

