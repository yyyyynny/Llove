// 로컬(기기 시간대) 기준 YYYY-MM-DD — toISOString()은 UTC라 한국 시간 자정 경계가 9시간 어긋남
function 오늘날짜_로컬(편차일){
  const d = new Date(Date.now() + (편차일 || 0) * 86400000);
  return d.getFullYear() + '-' + String(d.getMonth()+1).padStart(2,'0') + '-' + String(d.getDate()).padStart(2,'0');
}

// 연속·총 학습일 갱신 — 하루 1회만 동작 (KNOWLEDGE 13-1)
// 11-08 연속 보호(듀오링고 「스트릭 프리즈」 방식): 빠진 날 수만큼 보호를 써서 연속을 잇는다.
//   보호는 매주(월요일 시작) 처음 공부할 때 1개 생기고 최대 2개까지 쌓인다(구매 없음).
function 일수(날짜){ const [y,m,d] = 날짜.split('-').map(Number); return Math.round(Date.UTC(y, m-1, d) / 864e5); }
function 학습일갱신(){
  const 오늘 = 오늘날짜_로컬(0);
  if(사용자.마지막학습일 === 오늘) return;
  const 빈날 = 사용자.마지막학습일 ? 일수(오늘) - 일수(사용자.마지막학습일) - 1 : -1;
  if(빈날 === 0) 사용자.연속학습일 = (사용자.연속학습일 || 0) + 1;
  else if(빈날 > 0 && (사용자.얼음 || 0) >= 빈날){
    사용자.얼음 -= 빈날;
    사용자.연속학습일 = (사용자.연속학습일 || 0) + 1;
    showToastMsg(`연속 보호 ${빈날}개를 써서 연속 학습일을 지켰어요`);
  } else 사용자.연속학습일 = 1;
  const 이번주 = Math.floor((일수(오늘) + 3) / 7);   // 1970-01-01(목) 기준 +3 → 월요일 시작 주 번호
  if(사용자.얼음지급주 !== 이번주){ 사용자.얼음 = Math.min(2, (사용자.얼음 || 0) + 1); 사용자.얼음지급주 = 이번주; }
  사용자.총학습일 = (사용자.총학습일 || 0) + 1;
  사용자.마지막학습일 = 오늘;
  사용자데이터_저장({연속학습일:사용자.연속학습일, 총학습일:사용자.총학습일, 마지막학습일:오늘, 얼음:사용자.얼음, 얼음지급주:사용자.얼음지급주});
}

