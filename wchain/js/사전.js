// 따라서 이 파일은 이제 **로더**다. 단어는 `wchain/data/사전.json`에 있고 현재 비어 있다
// (관리자님이 유행어·줄임말을 직접 채울 칸). 게임의 사전 기준은 우리말샘이다.
//
// 원본 360단어는 버리지 않고 `tests/fixtures/원본사전.cjs`로 옮겼다 — 파이썬 대조는
// 고정 사전이 있어야 성립하므로 대조 기준으로만 계속 쓴다.
//
// 클래식 스크립트, 가장 먼저 로드.

// 보조 사전(우리말샘에 없는 말). 부팅 시 data/사전.json에서 채워진다.
// ⚠️ let인 이유: 로드 후 교체된다. 참조하는 쪽은 항상 이 변수를 읽어야 최신값을 본다
//    (구조 분해로 복사해 두면 빈 배열이 박제된다).
let 추가사전 = [];
let 사전_적재됨 = false;

async function 사전_로드(){
  try{
    const res = await fetch('data/사전.json');
    if(!res.ok) throw new Error('HTTP ' + res.status);
    const data = await res.json();
    추가사전 = Array.isArray(data && data.추가단어) ? data.추가단어.filter(w => typeof w === 'string') : [];
    사전_적재됨 = true;
  }catch(e){
    // 보조 사전은 없어도 게임이 돌아간다(기준은 우리말샘) — 경고만 남기고 빈 채로 진행.
    console.warn('[사전] data/사전.json 적재 실패 — 보조 사전 없이 진행합니다.', e);
    추가사전 = [];
    사전_적재됨 = false;
  }
  return 추가사전;
}

// jsdom/node 대조 테스트용 내보내기 (브라우저에선 무시)
if (typeof module !== 'undefined') module.exports = {
  사전_로드, get 추가사전(){ return 추가사전; }, get 사전_적재됨(){ return 사전_적재됨; }
};
