// 난이도의 **1차 기준**이었다. 그 결과 실제 플레이 공간(우리말샘 전체)과 판정 기준(280단어)이
// 어긋나 "정상 단어가 한방으로 오판돼 즉사" 같은 결함이 반복됐다.
//
// 관리자님 확정: **"90 정도를 온라인에 초점을 둔다. 내부 사전은 우리말샘에 없는 유행어·줄임말
// 등을 나중에 추가할 거니까 이번에 내부 사전 또한 빼고 연결해놔." / "일단 전부 삭제해둬."**
