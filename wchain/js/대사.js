// '잇는' 대사 — 코드에서 분리해 data/대사.json 한 곳으로 모음 (2026-07-29, 관리자님 지시).
// 2026-11-08 관리자님 결정: 페르소나(폭군·비서) 구분을 없애고 한 목소리로 통일했다 — 해요체 짧은
// 평서문, 사실 전달 위주, 칭찬·감탄은 드문 순간에만. 그래서 JSON은 `{ "키": "문구" }` 한 겹이다. **대사 추가·수정은 JSON만 건드리면 된다.**
// 키는 그 대사가 쓰이는 함수 이름 + 순번(예: user_defeat_1, 버튼_양보_1)이라 코드에서 역추적된다.
//
// 자리표시자: 중괄호. 두 가지를 모두 지원한다.
//   · 위치형 {0} {1}  → 대사(gs, '키', [값0, 값1])
//   · 이름형 {층}     → 대사(gs, '키', {층: gs.stage})
// 넘긴 값을 문구가 쓰지 않아도 괜찮다(문구만 바꿔 자리표시자를 빼도 코드는 그대로 둔다).
//
// 클래식 스크립트. 게임상태.js 뒤, 게임규칙.js·서바이벌.js보다 먼저 로드.

let 대사표 = {};

// data/대사.json 적재. index.html 부트스트랩이 기다리지 않고 뒤에서 받아 둔다(첫 화면엔 대사가 없음).
// 실패해도 게임이 멈추지는 않게 하되, 조용히 넘어가면 화면이 텅 비므로 반드시 표면화한다.
async function 대사_로드(){
  try{
    const res = await fetch('data/대사.json');
    if(!res.ok) throw new Error('HTTP ' + res.status);
    대사표 = await res.json();
  }catch(e){
    console.error('[대사] data/대사.json 적재 실패 — 대사가 키 이름으로 표시됩니다.', e);
  }
}

// 키로 문구를 꺼내 자리표시자를 채운다. gs 인자는 호출부 형태를 유지하려고 남겨 둔다.
// 값이 없으면(키 오타·적재 실패) 키 이름을 그대로 돌려줘 화면이 비지 않고 어디가 빠졌는지 보이게 한다.
// 옛 형식({폭군, 비서} 객체)이 브라우저 캐시로 남아 있어도 깨지지 않게 비서 칸을 읽는다.
function 대사(gs, 키, 값){
  const 항목 = 대사표[키];
  const 문구 = typeof 항목 === 'string' ? 항목 : 항목?.비서;
  if(!문구){
    console.warn('[대사] 키 없음:', 키);
    return `[대사 없음: ${키}]`;
  }
  if(값 === undefined || 값 === null) return 문구;
  return String(문구).replace(/\{([^{}]+)\}/g, (전체, 이름) => {
    // 위치형이면 배열 인덱스, 이름형이면 객체 키
    const v = Array.isArray(값) ? 값[Number(이름)] : 값[이름];
    return v === undefined ? 전체 : String(v);
  });
}

// 같은 상황에 여러 문구를 두고 하나를 무작위로 고르는 대사(정답 반응·AI 단어 반응 등).
// `접두_1`, `접두_2`, … 순번 키를 이어지는 데까지 훑는다 — 문구를 늘리려면 JSON에 다음 번호 키만 추가.
function 대사_무작위(gs, 접두, 값){
  const 후보 = [];
  for(let i = 1; 대사표[접두 + '_' + i]; i++) 후보.push(접두 + '_' + i);
  if(!후보.length){
    console.warn('[대사] 무작위 후보 없음:', 접두);
    return `[대사 없음: ${접두}]`;
  }
  return 대사(gs, 후보[Math.floor(Math.random() * 후보.length)], 값);
}
